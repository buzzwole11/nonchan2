class Paper(Base, TimestampMixin):
    """A work, after deduplication. One row per canonical paper (spec section 16)."""

    __tablename__ = "papers"
    __table_args__ = (
        vocab_check("open_access", "openAccessStatus"),
        vocab_check("retraction_status", "retractionStatus"),
        vocab_check("english_level", "englishLevel"),
        vocab_check("source_provider", "sourceProvider"),
        CheckConstraint("year BETWEEN 1600 AND 2200", name="ck_paper_year"),
        Index("ix_papers_primary_field_year", "primary_field_id", "year"),
        # The refresh worker's queue: "papers from this source, longest unchecked first".
        Index("ix_papers_refresh_queue", "source_provider", "last_refreshed_at"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UuidType, primary_key=True, default=_uuid)
    canonical_id: Mapped[str] = mapped_column(String(400), nullable=False, unique=True, index=True)
    title: Mapped[str] = mapped_column(Text, nullable=False)
    #: Normalised form used for last-resort duplicate detection (spec section 16).
    normalized_title: Mapped[str] = mapped_column(Text, nullable=False, index=True)
    #: Original English abstract. A translation never overwrites this column.
    abstract: Mapped[str] = mapped_column(Text, nullable=False)
    authors: Mapped[list[dict[str, Any]]] = mapped_column(JsonType, nullable=False, default=list)
    year: Mapped[int] = mapped_column(Integer, nullable=False)
    venue: Mapped[str | None] = mapped_column(String(400), nullable=True)
    paper_types: Mapped[list[str]] = mapped_column(JsonType, nullable=False, default=list)
    primary_field_id: Mapped[str | None] = mapped_column(
        String(64), ForeignKey("fields.id", ondelete="SET NULL"), nullable=True
    )
    open_access: Mapped[str] = mapped_column(String(16), nullable=False, default="unknown")
    retraction_status: Mapped[str] = mapped_column(String(32), nullable=False, default="none")
    version: Mapped[str | None] = mapped_column(String(32), nullable=True)
    supersedes_paper_id: Mapped[uuid.UUID | None] = mapped_column(
        UuidType, ForeignKey("papers.id", ondelete="SET NULL"), nullable=True
    )
    english_level: Mapped[str] = mapped_column(String(32), nullable=False, default="intermediate")
    math_density: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    equation_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    estimated_reading_minutes: Mapped[float] = mapped_column(Float, nullable=False, default=1.0)

    # Provenance (spec section 21) — every column here is required reading before display.
    source_provider: Mapped[str] = mapped_column(String(32), nullable=False)
    source_url: Mapped[str] = mapped_column(Text, nullable=False)
    pdf_url: Mapped[str | None] = mapped_column(Text, nullable=True)
    acquired_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    #: When the refresh worker last asked the source about this paper. Deliberately *not*
    #: `acquired_at`: section 21 defines that one as provenance — when this copy was taken,
    #: as the provider reports it — while this is our own operational note about when we
    #: last checked. Ordering the refresh queue by `acquired_at` looked equivalent and was
    #: not: a provider that echoes back a fixed timestamp leaves every paper permanently
    #: stale, so the queue re-checks the same batch forever and never reaches the rest.
    last_refreshed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    license_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    license_url: Mapped[str | None] = mapped_column(Text, nullable=True)
    #: False when the terms do not permit storing or re-showing the abstract text.
    abstract_redistributable: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    cache_policy: Mapped[str] = mapped_column(String(32), nullable=False, default="metadata_only")
    #: Everything the provider returned, kept so a re-parse never needs a re-fetch.
    raw_metadata: Mapped[dict[str, Any]] = mapped_column(JsonType, nullable=False, default=dict)

    identifiers: Mapped[list[PaperIdentifier]] = relationship(
        back_populates="paper", cascade="all, delete-orphan"
    )
    field_weights: Mapped[list[PaperField]] = relationship(
        back_populates="paper", cascade="all, delete-orphan"
    )


