"""SQLAlchemy models (spec section 23).

Two conventions run through the whole schema:

* **Vocabularies are ``VARCHAR`` with a ``CHECK`` constraint generated from
  ``packages/shared-types/enums.json``, not native PostgreSQL ``ENUM`` types.** Native
  enums require a migration and a table rewrite to add a value, which is exactly the kind
  of friction that leads to a hard-coded string sneaking in somewhere. A check constraint
  is regenerated from the shared file, and ``tests/test_vocab_parity.py`` fails if the
  database and the shared vocabulary disagree.

* **Provenance is not optional.** Anything derived from an external source carries its
  source, licence and acquisition time; anything generated by a model carries provider,
  model, prompt version and input hash (spec sections 21 and 23).
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    JSON,
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    Sequence,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

from papermatch_api import vocab

#: JSONB on PostgreSQL, plain JSON elsewhere, so unit tests can use SQLite.
JsonType = JSON().with_variant(JSONB(), "postgresql")
UuidType = UUID(as_uuid=True).with_variant(String(36), "sqlite")


class Base(DeclarativeBase):
    pass


def _uuid() -> uuid.UUID:
    return uuid.uuid4()


def vocab_check(column_name: str, vocabulary_key: str) -> CheckConstraint:
    """CHECK constraint listing every value of a shared vocabulary."""
    allowed = ", ".join(f"'{value}'" for value in vocab.values(vocabulary_key))
    return CheckConstraint(
        f"{column_name} IN ({allowed})",
        name=f"ck_{column_name}_{vocabulary_key.lower()}",
    )


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )


