/**
 * Bundles MathJax into a single self-contained string (spec sections 11, 25).
 *
 * Spec section 11 asks for three tiers — KaTeX, then MathJax, then the LaTeX source — and
 * this is the middle one. It exists for the formulas KaTeX refuses but that are still real
 * mathematics: `\substack`, `\bordermatrix`, AMS environments KaTeX has not implemented.
 * The reader gets a typeset formula instead of a monospaced string.
 *
 * **The SVG build, not the CHTML one, and the reason is not size.** `tex-chtml.js` is
 * ~400KB smaller, but its glyphs come from webfonts that MathJax injects an `@font-face`
 * rule for at runtime, from a base URL it computes itself. Inlining those would mean
 * rewriting a stylesheet this bundle generates rather than one it ships — and getting it
 * wrong means a formula that renders as blank boxes on a train. `tex-svg.js` carries every
 * glyph as a path inside the script: no fonts, no URLs, nothing to resolve. That also makes
 * the height we measure immediately after typesetting the real height, rather than the
 * height before a webfont finished loading.
 *
 * **This is a large file and that is the whole cost of the tier.** ~2MB of script,
 * committed. It is loaded only when KaTeX has already failed on a particular formula
 * (`MathView` escalates), so the common path never parses it — but it is in the app
 * bundle either way. DECISIONS.md D-062 records the measurement.
 *
 * Run with `npm run mathjax:build`. The output is committed, and CI regenerates it and
 * diffs, exactly as it does for KaTeX.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const MATHJAX = join(ROOT, 'node_modules', 'mathjax');
const OUT = join(ROOT, 'apps', 'mobile', 'src', 'math', 'mathjaxRuntime.ts');

const version = JSON.parse(readFileSync(join(MATHJAX, 'package.json'), 'utf8')).version;
const script = readFileSync(join(MATHJAX, 'es5', 'tex-svg.js'), 'utf8');

// Spec section 25 rules out fetching executable content at render time, and section 26
// requires the app to typeset on a train. So every URL left in this bundle has to be one
// nothing we enable can reach.
//
// Three survive, and all three belong to the Speech Rule Engine — MathJax's spoken-maths
// generator, which is pulled in by `a11y` and reached only through the `explorer` and
// `semantic-enrich` extensions. The document built in `mathjaxDocument.ts` enables
// neither, and takes its screen-reader output from `assistive-mml` instead, which is pure
// DOM. They are listed here by name rather than allowed by pattern: a *new* URL appearing
// in a future MathJax version must fail this build rather than pass a substring test.
// A fourth is the "About MathJax" link in the contextual menu (`ui/menu`), which the
// document turns off with `enableMenu: false`; the CSP would refuse the navigation in any
// case, and `MathView` refuses it a third time.
const ALLOWED_URLS = [
  'https://cdn.jsdelivr.net/npm/sre-mathmaps-ie@',
  'https://cdn.jsdelivr.net/npm/speech-rule-engine@',
  'https://cdn.jsdelivr.net/npm/wicked-good-xpath@1.3.0/dist/wgxpath.install.js',
  'https://www.mathjax.org',
];
const urls = [...new Set(script.match(/https?:\/\/[^"'\s)]+/g) ?? [])].filter(
  (url) => !url.startsWith('http://www.w3.org/') && !url.startsWith('https://www.w3.org/'),
);
const unexpected = urls.filter((url) => !ALLOWED_URLS.some((allowed) => url.startsWith(allowed)));
if (unexpected.length > 0) {
  throw new Error(
    `the MathJax build reaches for ${unexpected.length} unreviewed URL(s):\n  ${unexpected.join('\n  ')}\n` +
      'Each one has to be shown unreachable from the configuration in mathjaxDocument.ts before it is added to ALLOWED_URLS.',
  );
}
// Glyphs live in the script as paths. If this build ever needed font files, the renderer
// would silently draw nothing for characters it could not reach.
if (/url\((['"]?)[^)'"]*\.(woff2?|ttf)\1\)/.test(script)) {
  throw new Error('the MathJax build references font files, which are not shipped');
}

// Emitted with JSON.stringify rather than as a template literal: the minified script
// contains backticks, and `${` inside a template literal would start an interpolation.
const literal = (value) => JSON.stringify(value);

const digest = createHash('sha256').update(script).digest('hex').slice(0, 16);

const module = `/**
 * MathJax ${version} (\`tex-svg\`), inlined.
 *
 * GENERATED by scripts/build-mathjax-runtime.mjs — do not edit. Run \`npm run mathjax:build\`
 * after changing the MathJax version; CI regenerates this file and diffs it.
 *
 * MathJax is Apache-2.0 licensed (https://github.com/mathjax/MathJax/blob/master/LICENSE),
 * which permits redistribution in this form — what spec section 21 requires us to be able
 * to say about anything we ship.
 *
 * The SVG output carries every glyph as a path, so this needs no font files and no network
 * at any point (spec section 25). It is the second of spec section 11's three tiers and is
 * only reached when KaTeX has already refused the formula.
 */

export const MATHJAX_VERSION = '${version}';

/** Fingerprint of the embedded payload, so a test can tell it apart from a stale copy. */
export const MATHJAX_RUNTIME_DIGEST = '${digest}';

export const MATHJAX_SCRIPT = ${literal(script)};
`;

writeFileSync(OUT, module, 'utf8');

const kb = (n) => `${Math.round(n / 1024)}KB`;
console.log(
  `MathJax ${version} (tex-svg) -> ${OUT}\n` +
    `  script ${kb(script.length)}, no font files\n` +
    `  digest ${digest}`,
);
