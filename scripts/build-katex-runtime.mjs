/**
 * Bundles KaTeX into a single self-contained string (spec sections 11, 25).
 *
 * The renderer runs in a WebView with no network access — the app must typeset a formula
 * on a train, and spec section 25 rules out fetching anything at render time anyway. So
 * KaTeX's script, its stylesheet and its fonts are inlined here, at build time, into one
 * module the app imports.
 *
 * Only the `woff2` faces are kept. KaTeX ships woff2, woff and ttf of every face for the
 * benefit of browsers that no longer matter; the WebViews this app runs in (WKWebView and
 * Android System WebView) have supported woff2 for years, and keeping all three would
 * triple the payload for nothing. The `@font-face` rules for the other two formats are
 * dropped rather than left pointing at files that are not there, so a missing glyph shows
 * up as a missing glyph rather than as a silent network request.
 *
 * Run with `npm run katex:build`. The output is committed, and CI regenerates it and
 * diffs, the same way it does for the sample corpus — a generated file that has drifted
 * from its generator is worse than one that is not generated at all.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const KATEX = join(ROOT, 'node_modules', 'katex', 'dist');
const OUT = join(ROOT, 'apps', 'mobile', 'src', 'math', 'katexRuntime.ts');

const version = JSON.parse(
  readFileSync(join(ROOT, 'node_modules', 'katex', 'package.json'), 'utf8'),
).version;

const script = readFileSync(join(KATEX, 'katex.min.js'), 'utf8');
let css = readFileSync(join(KATEX, 'katex.min.css'), 'utf8');

// Inline every woff2 face; drop the woff and ttf sources that point at files we are not
// shipping.
const inlined = new Set();
css = css.replace(/url\(fonts\/([A-Za-z0-9_-]+\.woff2)\)/g, (_match, file) => {
  const data = readFileSync(join(KATEX, 'fonts', file));
  inlined.add(file);
  return `url(data:font/woff2;base64,${data.toString('base64')})`;
});
css = css.replace(
  /,?\s*url\(fonts\/[A-Za-z0-9_-]+\.(woff|ttf)\)\s*format\("(woff|truetype)"\)/g,
  '',
);

const leftover = css.match(/url\(fonts\//g);
if (leftover) {
  throw new Error(`${leftover.length} font reference(s) still point outside the bundle`);
}
if (inlined.size === 0) {
  throw new Error('no fonts were inlined; the CSS layout must have changed');
}

// Emitted with JSON.stringify rather than as a template literal: KaTeX's minified script
// contains backticks, and `${` in a template literal would start an interpolation. Getting
// this wrong produces a module that either does not parse or — worse — parses and evaluates
// part of the payload.
const literal = (value) => JSON.stringify(value);

const digest = createHash('sha256').update(script).update(css).digest('hex').slice(0, 16);

const module = `/**
 * KaTeX ${version}, inlined.
 *
 * GENERATED by scripts/build-katex-runtime.mjs — do not edit. Run \`npm run katex:build\`
 * after changing the KaTeX version; CI regenerates this file and diffs it.
 *
 * KaTeX is MIT licensed (https://github.com/KaTeX/KaTeX/blob/main/LICENSE); its fonts are
 * derived from the OFL-licensed Computer Modern faces. Both licences permit redistribution
 * in this form, which is what spec section 21 requires us to be able to say.
 *
 * ${inlined.size} woff2 faces are embedded as data URIs, so the renderer needs no network
 * at any point (spec section 25).
 */

export const KATEX_VERSION = '${version}';

/** Fingerprint of the embedded payload, so a test can tell it apart from a stale copy. */
export const KATEX_RUNTIME_DIGEST = '${digest}';

export const KATEX_SCRIPT = ${literal(script)};

export const KATEX_STYLES = ${literal(css)};
`;

writeFileSync(OUT, module, 'utf8');

const kb = (n) => `${Math.round(n / 1024)}KB`;
console.log(
  `KaTeX ${version} -> ${OUT}\n` +
    `  script ${kb(script.length)}, css ${kb(css.length)} (${inlined.size} woff2 faces inlined)\n` +
    `  digest ${digest}`,
);
